-- no unique key on message_id: the naive mode must be able to stamp a message twice
CREATE TABLE stamp
(
    stamp_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id     uuid        NOT NULL,
    sale_id        uuid        NOT NULL,
    card_id        text        NOT NULL,
    stamps         int         NOT NULL,
    body           text        NOT NULL,
    content_sha256 text        NOT NULL,
    applied_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX stamp_message_id_idx ON stamp (message_id);

--changeset spring-outbox-inbox:2
CREATE TABLE inbox
(
    consumer       text NOT NULL,
    message_id     uuid NOT NULL,
    content_sha256 text NOT NULL,
    duplicates     int  NOT NULL DEFAULT 0,
    PRIMARY KEY (consumer, message_id)
);
